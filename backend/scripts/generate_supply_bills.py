"""Regenerate the synthetic supply bills from the REAL company-001 sales.

Weekly supply use = real product sales x the assumed usage ratios. A simple reorder rule
(order when stock < 2 weeks of recent use; order 4 weeks of use, rounded up to packs)
then produces the bills. Deterministic (fixed seed). Output is disclosed as synthetic.

Run from backend/:  uv run python scripts/generate_supply_bills.py
"""

from __future__ import annotations

import math
import random
import sys
from datetime import timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import yaml  # noqa: E402

from app.config import FIXTURES_DIR  # noqa: E402
from app.planner.ratios import load_ratios  # noqa: E402
from app.planner.sales import load_fixture  # noqa: E402

BASE_PRICE = {"syn-gloves": 0.145, "syn-bakery-boxes": 0.81, "syn-bread-bags": 0.061, "syn-parchment": 0.048}
ITEMS = [
    ("syn-gloves", "Nitrile Gloves, Medium, Powder-Free", "Disposable food-safe nitrile gloves, size medium, powder-free.", "glove"),
    ("syn-bakery-boxes", "Bakery Box, White, 10 x 10 x 5 in", "White paperboard bakery boxes with window lid, 10 x 10 x 5 inches.", "box"),
    ("syn-parchment", "Parchment Pan Liner, Half Sheet", "Silicone-coated parchment paper liners for half sheet pans.", "sheet"),
    ("syn-bread-bags", "Bread Bag, Clear Poly, 8 x 4 x 18 in", "Clear polyethylene bread bags with gusset, 8 x 4 x 18 inches.", "bag"),
]


def main() -> None:
    rng = random.Random(17)
    sales = load_fixture()
    ratios = load_ratios()
    usage = {s: [sum(r.per_product.get(p, 0) * sales.series(p)[w] for p in r.per_product)
                 for w in range(sales.weeks)] for s, r in ratios.items()}
    stock = {s: 0.0 for s in ratios}
    started = {s: False for s in ratios}
    bills = []
    for week in range(sales.weeks):
        lines = []
        for sid, r in ratios.items():
            recent = [u for u in usage[sid][max(0, week - 3):week + 1] if u > 0]
            if not recent and usage[sid][week] == 0:
                continue
            weekly = sum(recent) / len(recent) if recent else usage[sid][week]
            if not started[sid] or stock[sid] < 2 * weekly:
                qty = math.ceil(max(4 * weekly - stock[sid], r.pack) / r.pack) * r.pack
                price = round(BASE_PRICE[sid] * rng.uniform(0.97, 1.04), 3)
                lines.append({"item_id": sid, "quantity": qty, "unit_price": f"{price}"})
                stock[sid] += qty
                started[sid] = True
        for sid in ratios:
            stock[sid] = max(0.0, stock[sid] - usage[sid][week])
        if lines:
            day = sales.week_start(week) + timedelta(days=1)
            bills.append({"id": f"bill-syn-{len(bills) + 1:04d}", "date": day.isoformat(), "lines": lines})

    doc = {
        "business_id": sales.business_id,
        "disclosure": (
            "Supply bills are synthetic. company-001's dataset bills contain only food items, so the team "
            "generated these from the company's REAL weekly sales times assumed packaging usage ratios "
            "(fixtures/usage_ratios.yaml) and a simple reorder rule."
        ),
        "vendor": {"id": "vend-syn-larkmoor", "name": "Larkmoor Foodservice Supply (fictional)",
                   "phone": "+10000000001", "email": "quotes@larkmoor.example"},
        "items": [{"item_id": i, "name": n, "description": d, "unit": u} for i, n, d, u in ITEMS],
        "bills": bills,
    }
    out = FIXTURES_DIR / "injected_supply_bills.yaml"
    header = ("# GENERATED by scripts/generate_supply_bills.py. Do not edit by hand.\n"
              "# Synthetic supply bills for company-001. Disclose in the submission.\n")
    out.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120))
    print(f"wrote {len(bills)} bills to {out}")
    for sid in ratios:
        print(f"  {sid}: total use {sum(usage[sid]):.0f}, stock at end {stock[sid]:.0f}, last 4 weeks use {usage[sid][-4:]}")


if __name__ == "__main__":
    main()
